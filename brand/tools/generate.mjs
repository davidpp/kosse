#!/usr/bin/env node
// Pinned build tools live beside this file. The app consumes generated assets only.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import sharp from "sharp";
import { wordmark } from "./wordmark.mjs";
import { relay, optical } from "./mark.mjs";
import { palette, colours, oklch } from "./palette.mjs";
const root = fileURLToPath(new URL("../", import.meta.url));
const C = colours(),
  D = colours(true);
const write = (name, data) => writeFileSync(root + name, data);
const provenance =
  "Original Kossé Relay artwork. Generated by brand/tools/generate.mjs from brand/tools/mark.mjs. MIT; wordmark uses Kibernetyk Mono SemiBold, OFL-1.1.";
const svg = (box, body, label = "Kossé") =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${box}" role="img" aria-label="${label}"><metadata>${provenance}</metadata>${body}</svg>\n`;
const raster = (source, size) =>
  sharp(Buffer.from(source))
    .resize(size, size)
    .withExif({ IFD0: { ImageDescription: provenance } })
    .png()
    .toBuffer();
const mark = (colour) => svg("0 0 100 100", relay(colour));
for (const [suffix, colour] of [
  ["", C.accent],
  ["-night", D.accent],
  ["-mono", "currentColor"],
])
  write(`kosse-mark${suffix}.svg`, mark(colour));

const font = readFileSync(root + "fonts/KibernetykMono-SemiBold.ttf");
const { path } = wordmark(font);
const bounds = path.getBoundingBox();
const w = bounds.x2 - bounds.x1,
  h = bounds.y2 - bounds.y1;
const word = (colour) => `<path fill="${colour}" d="${path.toPathData(3)}"/>`;
const lockup = (accent, ink) =>
  svg(
    `0 0 ${w + h * 1.5} ${h * 1.2}`,
    `<g transform="translate(0 ${h * 0.05}) scale(${(h * 1.1) / 100})">${relay(accent)}</g><g transform="translate(${h * 1.4 - bounds.x1} ${h * 0.1 - bounds.y1})">${word(ink)}</g>`,
  );
for (const [suffix, col] of [
  ["", C],
  ["-night", D],
]) {
  write(
    `kosse-wordmark${suffix}.svg`,
    svg(`${bounds.x1 - 1} ${bounds.y1 - 1} ${w + 2} ${h + 2}`, word(col.ink)),
  );
  write(`kosse-lockup${suffix}.svg`, lockup(col.accent, col.ink));
}

function squircle(inset, size, n = 5) {
  const half = size / 2,
    points = [];
  for (let i = 0; i < 360; i++) {
    const t = (i * Math.PI) / 180,
      c = Math.cos(t),
      s = Math.sin(t);
    points.push(
      [
        inset + half + half * Math.sign(c) * Math.abs(c) ** (2 / n),
        inset + half + half * Math.sign(s) * Math.abs(s) ** (2 / n),
      ]
        .map((v) => +v.toFixed(4))
        .join(" "),
    );
  }
  return `M${points.join("L")}Z`;
}
const icon = (small = false, favicon = false, preview = false) => {
  const inset = favicon ? 0 : 100,
    tile = 1024 - inset * 2,
    extent = tile * (small ? 0.88 : 0.92);
  const background = preview
    ? `<path fill="${C.accent}" d="${squircle(inset, tile)}"/><path fill="${C.canvas}" d="${squircle(inset + 34, tile - 68)}"/>`
    : `<path fill="${C.accent}" d="${squircle(inset, tile)}"/>`;
  const glyph = small
    ? optical(preview ? C.accent : "#FFFFFF", preview)
    : relay(preview ? C.accent : "#FFFFFF", preview);
  const grid = small ? 18 : 100;
  return svg(
    "0 0 1024 1024",
    `${background}<g transform="translate(${(1024 - extent) / 2} ${(1024 - extent) / 2}) scale(${extent / grid})">${glyph}</g>`,
    preview ? "Kossé preview" : "Kossé",
  );
};
const renders = [];
const writeRaster = (name, source, size) =>
  renders.push(raster(source, size).then((bytes) => write(name, bytes)));
for (const [suffix, preview] of [
  ["", false],
  ["-preview", true],
]) {
  write(`app-icon${suffix}.svg`, icon(false, false, preview));
  writeRaster(`app-icon${suffix}-1024.png`, icon(false, false, preview), 1024);
}
write("favicon.svg", icon(true, true));
writeRaster("favicon-32.png", icon(true, true), 32);
mkdirSync(root + "tray", { recursive: true });
const states = ["default", "attention", "preview", "preview-attention"];
for (const state of states) {
  const source = svg(
    "0 0 18 18",
    optical("#000000", state.startsWith("preview"), state.endsWith("attention")),
    `Kossé ${state}`,
  );
  write(`tray/tray-${state}.svg`, source);
  for (const scale of [1, 2])
    writeRaster(`tray/tray-${state}${scale === 2 ? "@2x" : ""}.png`, source, 18 * scale);
}
write("tray/tray-16.svg", svg("0 0 16 16", optical("#000000", false, false, 16)));
for (const scale of [1, 2])
  writeRaster(
    `tray/tray-16${scale === 2 ? "@2x" : ""}.png`,
    svg("0 0 16 16", optical("#000000", false, false, 16)),
    16 * scale,
  );
for (const [name, preview] of [
  ["Kosse", false],
  ["Kosse-preview", true],
]) {
  mkdirSync(root + `${name}.iconset`, { recursive: true });
  for (const size of [16, 32, 128, 256, 512])
    for (const scale of [1, 2])
      writeRaster(
        `${name}.iconset/icon_${size}x${size}${scale === 2 ? "@2x" : ""}.png`,
        icon(size <= 32, false, preview),
        size * scale,
      );
}
await Promise.all(renders);
for (const name of ["Kosse", "Kosse-preview"]) {
  execFileSync("/usr/bin/iconutil", [
    "-c",
    "icns",
    root + `${name}.iconset`,
    "-o",
    root + `${name}.icns`,
  ]);
}

const tokens = {
  $description:
    "Kossé — Relay. Neutral surfaces and Québec-inspired blue. W3C DTCG OKLCH tokens; hex preserves the authored sRGB source.",
};
for (const [scheme, dark] of [
  ["light", false],
  ["dark", true],
]) {
  tokens[scheme] = {};
  for (const p of palette) {
    const hex = p[dark ? 4 : 3],
      components = oklch(hex);
    tokens[scheme][p[0]] = {
      $type: "color",
      $description: `${p[1]} — ${p[2]}.`,
      $value:
        p[0] === "danger" ? `{${scheme}.failed}` : { colorSpace: "oklch", components, alpha: 1 },
      $extensions: { "design.kosse": { hex, ...(p[0] === "danger" ? { oklch: components } : {}) } },
    };
  }
  for (const role of ["accent", "danger"]) {
    const target = dark ? "canvas" : "surface",
      hex = (dark ? D : C)[target];
    tokens[scheme][`on-${role}`] = {
      $type: "color",
      $description: `Text on solid ${role} buttons.`,
      $value: `{${scheme}.${target}}`,
      $extensions: { "design.kosse": { hex, oklch: oklch(hex) } },
    };
  }
}
// Keep the three-component colour tuples in the repository formatter's compact form.
write(
  "tokens.json",
  JSON.stringify(tokens, null, 2).replace(
    /\[\s+(-?[\d.]+),\s+(-?[\d.]+),\s+(-?[\d.]+)\s+\]/g,
    "[$1, $2, $3]",
  ) + "\n",
);

// Inspectable contact sheet; tray examples are the exported pixels, not fresh approximations.
const layers = [];
const add = (input, left, top) => layers.push({ input, left, top });
const label = (text, x, y, size = 18, colour = C.ink) =>
  `<text x="${x}" y="${y}" font-family="Helvetica,Arial,sans-serif" font-size="${size}" fill="${colour}">${text}</text>`;
let sheet =
  `<rect width="1440" height="1160" fill="${C.canvas}"/>` +
  label("Kossé / Relay", 40, 50, 28) +
  label("Kibernetyk Mono SemiBold · Québec-inspired blue #003DA5", 40, 82, 17);
add(
  await sharp(Buffer.from(lockup(C.accent, C.ink)))
    .resize({ width: 540 })
    .png()
    .toBuffer(),
  40,
  125,
);
sheet += `<rect x="740" y="110" width="660" height="180" fill="${D.canvas}"/>`;
add(
  await sharp(Buffer.from(lockup(D.accent, D.ink)))
    .resize({ width: 540 })
    .png()
    .toBuffer(),
  780,
  135,
);
sheet +=
  label("Release", 40, 350) +
  label("Preview · split stem, pale tile", 400, 350) +
  label("Tray · default / attention / preview / preview attention", 780, 350);
add(await raster(icon(), 300), 40, 365);
add(await raster(icon(false, false, true), 300), 400, 365);
const trayPixels = states.map((state) => readFileSync(root + `tray/tray-${state}@2x.png`));
const invertedTrayPixels = await Promise.all(
  trayPixels.map((input) => sharp(input).negate({ alpha: false }).png().toBuffer()),
);
for (const [i, bg, inverted] of [
  [0, "#DEDEE0", false],
  [1, "#35353B", true],
]) {
  const y = 380 + i * 85;
  sheet += `<rect x="780" y="${y}" width="620" height="65" fill="${bg}"/>`;
  for (let j = 0; j < states.length; j++) {
    add(inverted ? invertedTrayPixels[j] : trayPixels[j], 810 + j * 150, y + 14);
  }
}
sheet +=
  label("Optical 18 · 1 px gap, 3 px stem, 2.5 px arms", 780, 595, 17) +
  label("Dedicated 16 px version", 780, 630, 17);
add(readFileSync(root + "tray/tray-16.png"), 1030, 616);
sheet += label("Small app icons · release / preview", 40, 710, 18);
for (const [j, name] of ["Kosse", "Kosse-preview"].entries())
  for (const [i, size] of [16, 32, 128].entries())
    add(
      readFileSync(root + `${name}.iconset/icon_${size}x${size}.png`),
      40 + j * 350 + i * 80,
      735,
    );
sheet += label("Neutral surfaces, blue selection, explicit observation colours", 780, 710, 18);
for (const [i, p] of palette
  .filter((entry) => ["canvas", "surface", "ink", "accent", "stale", "danger"].includes(entry[0]))
  .entries()) {
  const x = 780 + (i % 3) * 205,
    y = 745 + Math.floor(i / 3) * 100;
  sheet +=
    `<rect x="${x}" y="${y}" width="82" height="40" fill="${p[3]}"/><rect x="${x + 86}" y="${y}" width="82" height="40" fill="${p[4]}"/>` +
    label(p[0], x, y + 62, 14);
}
sheet +=
  label(
    "Original Relay artwork · MIT. Kibernetyk Mono by Pavlo Kilko / Project Authors · SIL OFL 1.1.",
    40,
    1070,
    15,
  ) +
  label(
    "Native template tint, Dock appearance and pointer-level fit remain checks in the real app.",
    40,
    1100,
    15,
  );
await sharp(Buffer.from(svg("0 0 1440 1160", sheet)))
  .composite(layers)
  .withExif({ IFD0: { ImageDescription: provenance } })
  .png()
  .toFile(root + "preview.png");
